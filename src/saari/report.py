"""Compile a saaristo corpus into systematic-literature-review (SLR) artifacts.

This module turns the corpus + screening decisions + study protocol into the
*reporting* layer of an SLR: a PRISMA 2020 flow diagram, a Markdown manuscript
scaffold, and a Marp slide deck. `export.py` wraps these with file-writing
entry points; the CLI / MCP / HTTP surfaces call those.

Design principle — **never fabricate**. Everything mechanical and true is
auto-filled and traces to a source:

- counts come from `study.funnel()` (the DB),
- references from the `included` papers,
- theme headings from OpenAlex's *own* per-paper topic classification
  (factual metadata kept in `.saaristo/raw/openalex/<id>.json`),
- every exclusion reason from a recorded `screening_note`.

Interpretive prose (background, per-theme synthesis, discussion) is emitted as
visible ``<!-- WRITE: ... -->`` slots — a human or an LLM authors it, saari
never invents it. An honest Limitations block is auto-written so the draft
cannot overclaim (single source, single reviewer, abstract-only screening, no
registration).

The pure builder/render functions take injected data so they are unit-testable
without a database; the ``*_data`` / ``landscape_points`` wrappers do the DB I/O.
"""

from __future__ import annotations

import html
import json
from pathlib import Path
from typing import Any

from saari import db, paths, projection, study
from saari.export import _citation_key
from saari.models import Paper

BANNER = (
    "<!--\n"
    "  Generated by saari (`saari export`). Mechanical content below — counts,\n"
    "  tables, references, figures — is auto-filled and traces to the corpus DB.\n"
    "  Lines marked `<!-- WRITE: ... -->` are synthesis slots: a human or an LLM\n"
    "  must author them. saari does not invent findings. Verify every claim\n"
    "  against the cited sources before submission.\n"
    "-->\n"
)


def _slot(label: str) -> str:
    """A visible authoring slot: an HTML comment plus an italic placeholder."""
    return f"<!-- WRITE: {label} -->\n\n_[{label} — to be written.]_\n"


# --------------------------------------------------------------------------- #
# PRISMA flow
# --------------------------------------------------------------------------- #

def build_prisma(funnel: dict[str, Any], excluded: list[Paper]) -> dict[str, Any]:
    """Assemble a PRISMA 2020 flow structure from a funnel dict + excluded papers.

    Pure: give it `study.funnel()` output and the list of `excluded` papers and
    it returns the flow numbers, splitting identification by search `source`
    (database searches vs snowballing) and bucketing exclusions by their
    recorded `screening_note`.
    """
    searches = funnel.get("searches", [])
    by_source: dict[str, int] = {}
    for s in searches:
        src = (s.get("source") or "unknown").strip() or "unknown"
        by_source[src] = by_source.get(src, 0) + int(s.get("n_returned") or 0)
    n_snowball = by_source.get("snowball", 0)
    n_database = sum(v for k, v in by_source.items() if k != "snowball")

    n_fetched = int(funnel.get("n_fetched", 0))
    n_unique = int(funnel.get("n_unique", 0))
    # Papers can enter the corpus outside any recorded search event (added
    # directly by id, seeded, etc.). Attribute those to an "other" bucket so
    # the funnel stays arithmetically consistent: identified >= unique, and
    # duplicates removed is exact instead of clamped.
    n_other = max(n_unique - n_fetched, 0)
    n_total = n_fetched + n_other
    n_duplicates_removed = n_total - n_unique

    by_status = funnel.get("by_status", {})
    n_included = int(by_status.get("included", 0))
    n_excluded = int(by_status.get("excluded", 0))
    n_maybe = int(by_status.get("maybe", 0))
    n_candidate = int(by_status.get("candidate", 0))
    n_screened = n_included + n_excluded + n_maybe

    reasons: dict[str, int] = {}
    for p in excluded:
        note = (p.screening_note or "").strip() or "no reason recorded"
        reasons[note] = reasons.get(note, 0) + 1

    return {
        "identification": {
            "by_source": by_source,
            "n_database": n_database,
            "n_snowball": n_snowball,
            "n_other": n_other,
            "n_total": n_total,
        },
        "n_duplicates_removed": n_duplicates_removed,
        "n_unique": n_unique,
        "n_screened": n_screened,
        "n_unscreened": n_candidate,
        "n_maybe": n_maybe,
        "excluded": {"n": n_excluded, "reasons": dict(sorted(reasons.items(), key=lambda kv: -kv[1]))},
        "n_included": n_included,
    }


def prisma_data(project_root: Path | None = None) -> dict[str, Any]:
    """DB wrapper: `study.funnel()` + excluded papers -> `build_prisma()`."""
    root = project_root or paths.project_root()
    funnel = study.funnel(root)
    with db.connect(paths.db_path(root)) as con:
        excluded = db.list_papers(
            con, limit=1_000_000, status="excluded", order_by="first_seen_at ASC"
        )
    return build_prisma(funnel, excluded)


def _reasons_lines(reasons: dict[str, int]) -> str:
    if not reasons:
        return "no exclusions recorded"
    return "; ".join(f"{note} (n={n})" for note, n in reasons.items())


def render_prisma_mermaid(data: dict[str, Any]) -> str:
    """PRISMA flow as a Mermaid `flowchart` (renders on GitHub / via Pandoc)."""
    idn = data["identification"]
    src_line = f"database searches: {idn['n_database']} · snowballing: {idn['n_snowball']}"
    if idn.get("n_other"):
        src_line += f" · other: {idn['n_other']}"
    ident = f"Records identified (n={idn['n_total']})<br/>{src_line}"
    dedup = f"Records after duplicates removed (n={data['n_unique']})<br/>duplicates removed: {data['n_duplicates_removed']}"
    screened = f"Records screened (n={data['n_screened']})"
    if data["n_unscreened"]:
        screened += f"<br/>awaiting screening: {data['n_unscreened']}"
    excluded = f"Records excluded (n={data['excluded']['n']})<br/>{_reasons_lines(data['excluded']['reasons'])}"
    included = f"Studies included in review (n={data['n_included']})"
    return (
        "flowchart TD\n"
        f'    A["{ident}"] --> B["{dedup}"]\n'
        f'    B --> C["{screened}"]\n'
        f'    C --> X["{excluded}"]\n'
        f'    C --> D["{included}"]\n'
    )


def _svg_box(x: int, y: int, w: int, h: int, lines: list[str]) -> str:
    parts = [
        f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" '
        f'fill="#f5f7fa" stroke="#334155" stroke-width="1.5"/>'
    ]
    line_h = 18
    ty = y + 24
    for ln in lines:
        parts.append(
            f'<text x="{x + w // 2}" y="{ty}" text-anchor="middle" '
            f'font-family="sans-serif" font-size="13" fill="#0f172a">{html.escape(ln)}</text>'
        )
        ty += line_h
    return "\n".join(parts)


def _svg_arrow(x1: int, y1: int, x2: int, y2: int) -> str:
    return (
        f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="#334155" '
        f'stroke-width="1.5" marker-end="url(#arrow)"/>'
    )


def render_prisma_svg(data: dict[str, Any]) -> str:
    """PRISMA flow as a self-contained, dependency-free SVG (fixed layout)."""
    idn = data["identification"]
    reasons = data["excluded"]["reasons"]
    reason_lines = [f"{note} (n={n})" for note, n in list(reasons.items())[:4]] or ["no reasons recorded"]
    # The side box is 250px wide with centered, non-wrapping text.
    reason_lines = [ln if len(ln) <= 36 else ln[:33] + "..." for ln in reason_lines]

    W, H = 840, 620
    bx, bw = 210, 300  # main column x, width
    boxes = [
        _svg_box(bx, 20, bw, 70, [
            f"Records identified (n={idn['n_total']})",
            f"database: {idn['n_database']}  ·  snowballing: {idn['n_snowball']}"
            + (f"  ·  other: {idn['n_other']}" if idn.get("n_other") else ""),
        ]),
        _svg_box(bx, 160, bw, 70, [
            f"Records after de-duplication (n={data['n_unique']})",
            f"duplicates removed: {data['n_duplicates_removed']}",
        ]),
        _svg_box(bx, 300, bw, 50, [
            f"Records screened (n={data['n_screened']})",
            *( [f"awaiting screening: {data['n_unscreened']}"] if data["n_unscreened"] else [] ),
        ]),
        _svg_box(bx, 470, bw, 50, [
            f"Studies included (n={data['n_included']})",
        ]),
        # side box: exclusions with reasons
        _svg_box(bx + bw + 40, 300, 250, 20 + 18 * (len(reason_lines) + 1), [
            f"Records excluded (n={data['excluded']['n']})",
            *reason_lines,
        ]),
    ]
    arrows = [
        _svg_arrow(bx + bw // 2, 90, bx + bw // 2, 160),
        _svg_arrow(bx + bw // 2, 230, bx + bw // 2, 300),
        _svg_arrow(bx + bw // 2, 350, bx + bw // 2, 470),
        _svg_arrow(bx + bw, 325, bx + bw + 40, 325),
    ]
    defs = (
        '<defs><marker id="arrow" markerWidth="10" markerHeight="10" refX="8" refY="3" '
        'orient="auto" markerUnits="strokeWidth">'
        '<path d="M0,0 L8,3 L0,6 Z" fill="#334155"/></marker></defs>'
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" '
        f'viewBox="0 0 {W} {H}" role="img" aria-label="PRISMA flow diagram">\n'
        f"{defs}\n" + "\n".join(boxes + arrows) + "\n</svg>\n"
    )


# --------------------------------------------------------------------------- #
# Thematic grouping (from OpenAlex topics — factual, not invented)
# --------------------------------------------------------------------------- #

def _primary_topic_label(topics: list[dict]) -> str | None:
    """Label of a paper's primary (top-ranked) OpenAlex topic.

    Prefers the specific topic name (e.g. 'Semantic Web and Ontologies') over the
    coarse `subfield`/`field` (which collapse a whole corpus into 'Artificial
    Intelligence' / 'Computer Science'), falling back up the hierarchy.
    """
    if not topics:
        return None
    top = topics[0]
    for key in ("display_name",):
        if top.get(key):
            return top[key]
    for level in ("subfield", "field", "domain"):
        v = (top.get(level) or {}).get("display_name")
        if v:
            return v
    return None


def group_by_topic(
    papers: list[Paper], topic_field: dict[str, str | None]
) -> dict[str, list[Paper]]:
    """Group papers by their primary-topic field. Pure: `topic_field` maps
    paper.id -> field name (or None). Missing -> 'Uncategorized'. Groups are
    ordered by size (largest theme first), 'Uncategorized' always last.
    """
    groups: dict[str, list[Paper]] = {}
    for p in papers:
        theme = topic_field.get(p.id) or "Uncategorized"
        groups.setdefault(theme, []).append(p)
    ordered = sorted(
        groups.items(),
        key=lambda kv: (kv[0] == "Uncategorized", -len(kv[1]), kv[0]),
    )
    return dict(ordered)


def theme_groups(
    project_root: Path | None = None, status: str | None = "included"
) -> dict[str, list[Paper]]:
    """DB+raw wrapper: group `status` papers by OpenAlex primary-topic field."""
    root = project_root or paths.project_root()
    with db.connect(paths.db_path(root)) as con:
        papers = db.list_papers(
            con, limit=1_000_000, status=status,
            order_by="cited_by_count DESC NULLS LAST",
        )
        topic_field: dict[str, str | None] = {}
        for p in papers:
            raw_rel = db.get_raw_path(con, p.id)
            topics: list[dict] = []
            if raw_rel:
                full = root / raw_rel
                if full.exists():
                    try:
                        topics = json.loads(full.read_text()).get("topics") or []
                    except (OSError, json.JSONDecodeError):
                        topics = []
            topic_field[p.id] = _primary_topic_label(topics)
    return group_by_topic(papers, topic_field)


