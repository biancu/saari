def _authors_short(p: Paper) -> str:
    names = [a.name for a in p.authors if getattr(a, "name", None)]
    if not names:
        return "—"
    first = names[0].split()[-1] if names[0].split() else names[0]
    return first if len(names) == 1 else f"{first} et al."


def characteristics_table(papers: list[Paper]) -> str:
    """Study-characteristics table — mechanical columns only (no interpretation)."""
    header = (
        "| Cite key | Authors | Year | Venue | Citations | OA | DOI |\n"
        "|---|---|---|---|---|---|---|\n"
    )
    rows = []
    for p in papers:
        doi = f"[{p.doi}](https://doi.org/{p.doi})" if p.doi else "—"
        rows.append(
            f"| `{_citation_key(p)}` | {_authors_short(p)} | {p.year or '—'} | "
            f"{(p.venue or '—')} | {p.cited_by_count if p.cited_by_count is not None else '—'} | "
            f"{p.oa_status or '—'} | {doi} |"
        )
    return header + "\n".join(rows) + "\n"


def search_strategy_table(searches: list[dict[str, Any]]) -> str:
    header = "| # | Source | Query | Date | Records |\n|---|---|---|---|---|\n"
    rows = []
    for i, s in enumerate(searches, 1):
        date = (s.get("created_at") or "")[:10]
        rows.append(
            f"| {i} | {s.get('source', '—')} | `{s.get('query', '')}` | {date} | {s.get('n_returned', '—')} |"
        )
    return header + "\n".join(rows) + "\n"


def reference_list(papers: list[Paper]) -> str:
    """Numbered reference list keyed by the same cite keys as the BibTeX export."""
    lines = []
    for i, p in enumerate(papers, 1):
        authors = ", ".join(a.name for a in p.authors if getattr(a, "name", None)) or "—"
        venue = f" *{p.venue}*." if p.venue else ""
        doi = f" https://doi.org/{p.doi}" if p.doi else ""
        lines.append(f"{i}. [`{_citation_key(p)}`] {authors} ({p.year or 'n.d.'}). {p.title}.{venue}{doi}")
    return "\n".join(lines) + "\n"


def limitations_block(by_source: dict[str, int] | None = None) -> str:
    """Auto-disclosed method limitations so the draft cannot overclaim.

    `by_source` (record counts per search source) makes the sources bullet
    factual: single-source wording only when a single database was used.
    """
    databases = sorted(k for k in (by_source or {}) if k not in ("snowball", "unknown"))
    if len(databases) > 1:
        src_bullet = (
            f"- **Bibliographic sources.** Records were identified via {len(databases)} "
            f"databases ({', '.join(databases)}) plus citation snowballing. Coverage is "
            "bounded by these databases' indexing and English-language metadata.\n"
        )
    else:
        db_name = databases[0] if databases else "OpenAlex"
        src_bullet = (
            f"- **Single bibliographic source.** Records were identified via the {db_name} API "
            "(plus citation snowballing), not multiple databases (e.g. Scopus, Web of Science, "
            f"IEEE Xplore). Coverage is bounded by {db_name} indexing and English-language metadata.\n"
        )
    return (
        "This review was produced with saari and carries the following method limitations, "
        "which readers should weigh:\n\n"
        + src_bullet
        + "- **Single-reviewer screening.** Inclusion/exclusion decisions were made by a single "
        "reviewer (human or LLM agent). There was no second independent reviewer and no "
        "inter-rater agreement statistic (e.g. Cohen's κ).\n"
        "- **Title/abstract screening only.** Unless full texts were separately retrieved and "
        "recorded, screening relied on titles and abstracts.\n"
        "- **No formal risk-of-bias / quality appraisal** was applied to included studies "
        "unless recorded separately.\n"
        "- **No prospective registration.** This protocol was not registered on PROSPERO or OSF.\n"
    )


