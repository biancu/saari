_STATUS_COLORS = {
    "included": "#16a34a",
    "excluded": "#cbd5e1",
    "maybe": "#f59e0b",
    "candidate": "#94a3b8",
}


def render_landscape_svg(points: list[dict[str, Any]], width: int = 720, height: int = 520) -> str:
    """Static SVG scatter of the 2D projection, colored by screening status.

    Pure: `points` = [{x, y, status, title, cited}]. Complements the existing
    interactive `landscape.html`; this one is print-ready for the manuscript.
    """
    if not points:
        return (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}">'
            f'<text x="20" y="30" font-family="sans-serif" font-size="14">No projection — run `saari refresh`.</text>'
            f"</svg>\n"
        )
    margin = 40
    xs = [p["x"] for p in points]
    ys = [p["y"] for p in points]
    min_x, max_x = min(xs), max(xs)
    min_y, max_y = min(ys), max(ys)
    span_x = max(max_x - min_x, 1e-9)
    span_y = max(max_y - min_y, 1e-9)
    aw, ah = width - 2 * margin, height - 2 * margin

    circles = []
    for p in points:
        cx = margin + (p["x"] - min_x) / span_x * aw
        cy = margin + (p["y"] - min_y) / span_y * ah
        cited = int(p.get("cited") or 0)
        r = 3 + min(9.0, (cited ** 0.5) / 6.0)
        color = _STATUS_COLORS.get(p.get("status", "candidate"), "#94a3b8")
        title = html.escape(str(p.get("title") or ""))[:120]
        circles.append(
            f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r:.1f}" fill="{color}" '
            f'fill-opacity="0.75" stroke="#334155" stroke-width="0.4"><title>{title}</title></circle>'
        )
    # legend
    legend = []
    lx, ly = margin, height - 14
    for status, color in _STATUS_COLORS.items():
        legend.append(
            f'<circle cx="{lx}" cy="{ly}" r="5" fill="{color}"/>'
            f'<text x="{lx + 10}" y="{ly + 4}" font-family="sans-serif" font-size="11" fill="#334155">{status}</text>'
        )
        lx += 110
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-label="Corpus landscape">\n'
        f'<rect width="{width}" height="{height}" fill="#ffffff"/>\n'
        + "\n".join(circles) + "\n" + "\n".join(legend) + "\n</svg>\n"
    )


def landscape_points(
    project_root: Path | None = None, status: str | None = None
) -> list[dict[str, Any]]:
    """DB wrapper: join the 2D projection with paper metadata for the scatter."""
    root = project_root or paths.project_root()
    proj = {d["paper_id"]: (d["x"], d["y"]) for d in projection.get_projection(root)}
    with db.connect(paths.db_path(root)) as con:
        papers = db.list_papers(con, limit=1_000_000, status=status)
    pts: list[dict[str, Any]] = []
    for p in papers:
        if p.id in proj:
            x, y = proj[p.id]
            pts.append({
                "x": x, "y": y, "status": p.status,
                "title": p.title, "cited": p.cited_by_count or 0,
            })
    return pts


